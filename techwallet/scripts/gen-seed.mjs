// Generates supabase/seed.sql from src/lib/data.ts
// Usage: node scripts/gen-seed.mjs
import { writeFileSync } from "node:fs";
import { products } from "../src/lib/data.ts";

const q = (v) => (v == null ? "null" : `'${String(v).replace(/'/g, "''")}'`);

const rows = products.map(
  (p) =>
    `(${q(p.slug)}, ${q(p.name)}, ${q(p.category)}, ${q(p.brand)}, ${p.price}, ${p.compare ?? "null"}, ${p.stock}, ${q(p.tag)}, ${q(p.short)}, ${q(JSON.stringify(p.specs))}::jsonb)`,
);

const sql = `-- Generated by scripts/gen-seed.mjs. Safe to re-run (upserts by slug).
insert into products (slug, name, category, brand, price, compare_price, stock, tag, short, specs) values
${rows.join(",\n")}
on conflict (slug) do update set
  name = excluded.name, category = excluded.category, brand = excluded.brand,
  price = excluded.price, compare_price = excluded.compare_price, stock = excluded.stock,
  tag = excluded.tag, short = excluded.short, specs = excluded.specs;
`;

writeFileSync(new URL("../supabase/seed.sql", import.meta.url), sql);
console.log(`Wrote supabase/seed.sql with ${products.length} products`);
